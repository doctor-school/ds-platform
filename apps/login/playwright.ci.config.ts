import { defineConfig, devices } from "@playwright/test";
import { prCiDoorTags } from "@ds/e2e/host-tags";
import { defineBddConfig } from "playwright-bdd";

/**
 * The sign-in host's CI tier (`playwright-axe-login`, #3170): the production
 * build behind `next start`, its api upstream a double answering only the
 * entry read (`e2e/support/sign-in-entry-api.mjs`). The build must have been
 * made with `API_PROXY_TARGET` pointing at the double (ci.yml does).
 *
 * Two projects. `chromium` runs the app-local door specs (`e2e/*.e2e.spec.ts`).
 * `door-scenarios` (#3345 item 4) runs the 003 catalog's sign-in-host bindings
 * tagged `@pr-ci:login` — the scenarios themselves, through the shared
 * `packages/e2e` step definitions, generated by `bddgen` with
 * `missingSteps: "fail-on-gen"` so a tagged scenario this tier cannot execute
 * fails generation rather than skipping. Its journeys start on the Academy
 * entry, which here is the double's storefront-entry origin
 * (`LOGIN_FAKE_STOREFRONT_PORT`): it answers each entry's 303 onto this host's
 * door the way the IdP lands it, and nothing more. The bindings that need what
 * the double has none of carry `@stage-only:login(<class>)` and run only in the
 * stage suite's `login` project (`tools/lint/scenario-coverage-lint.ts`).
 */
const PORT = Number(process.env.LOGIN_CI_PORT ?? 3215);
const API_PORT = Number(process.env.LOGIN_FAKE_API_PORT ?? 3216);
const STOREFRONT_PORT = Number(process.env.LOGIN_FAKE_STOREFRONT_PORT ?? 3217);
const BASE = `http://127.0.0.1:${PORT}`;
const API = `http://127.0.0.1:${API_PORT}`;
const STOREFRONT = `http://127.0.0.1:${STOREFRONT_PORT}`;

// The shared steps read the Academy origin from the `academy` host config's
// variable (`packages/e2e/hosts.ts`); on this tier it is the entry double.
process.env.E2E_PORTAL_URL = STOREFRONT;

const doorScenariosDir = defineBddConfig({
  features:
    "../docs/content/specs/features/003-user-authentication/003-scenarios.feature",
  featuresRoot: "../docs/content/specs/features",
  steps: ["../../packages/e2e/steps/**/*.ts"],
  outputDir: ".features-gen/door-scenarios",
  tags: prCiDoorTags(),
  missingSteps: "fail-on-gen",
});

export default defineConfig({
  fullyParallel: true,
  forbidOnly: !!process.env.CI,
  retries: process.env.CI ? 1 : 0,
  reporter: [["list"]],
  timeout: 30_000,
  expect: { timeout: 10_000 },
  use: { baseURL: BASE, trace: "retain-on-failure" },
  projects: [
    {
      name: "chromium",
      testDir: "./e2e",
      use: { ...devices["Desktop Chrome"] },
    },
    {
      name: "door-scenarios",
      testDir: doorScenariosDir,
      // The `host` fixture reads the storefront the journey starts on here.
      metadata: { storefront: "academy" },
      use: { ...devices["Desktop Chrome"], locale: "ru-RU" },
    },
  ],
  webServer: [
    {
      command: "node e2e/support/sign-in-entry-api.mjs",
      url: `${API}/health`,
      env: {
        LOGIN_FAKE_API_PORT: String(API_PORT),
        LOGIN_FAKE_STOREFRONT_PORT: String(STOREFRONT_PORT),
        LOGIN_CI_PORT: String(PORT),
      },
      timeout: 30_000,
      reuseExistingServer: false,
    },
    {
      command: `pnpm --filter @ds/login exec next start -H 0.0.0.0 -p ${PORT} --keepAliveTimeout 125000`,
      url: `${BASE}/icon.svg`,
      // 003 EARS-72 — the refusal page's way out names both storefronts,
      // read at request time from the storefronts' own origin variables.
      env: {
        API_PROXY_TARGET: API,
        ACADEMY_PUBLIC_ORIGIN: "http://localhost:3001",
        DOCTOR_PUBLIC_ORIGIN: "http://localhost:3004",
      },
      timeout: 120_000,
      reuseExistingServer: false,
    },
  ],
});
