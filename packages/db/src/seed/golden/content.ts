// sentence per эфир, eight experts without photographs, five projects — so the
// banks below are sized for a production-shaped catalogue, not for a floor.
//
// Rules, all load-bearing:
//   * literal, curated Russian in the register the product actually uses. No
//     generated filler, no lorem, no «Описание события 17»;
//   * zero randomness: every composition is an index-derived function of the
//     row's ordinal, so two builds at the same pin are byte-identical;
//   * the programme list is append-only. Volume events consume it POSITIONALLY,
//     so inserting a title in the middle silently re-titles every event after
//     it and invalidates any recorded walk of the stand.

