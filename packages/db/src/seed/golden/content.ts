/**
 * Composes an event description from the banks. Pure and index-derived.
 *
 * Three to five paragraphs, joined by a blank line — the shape
 * `event-page-view` renders and the shape the owner rejected in PR #2216.
 * Neighbouring ordinals can never produce the same text: the context paragraph
 * alternates on `i % 2`, so two adjacent events differ in their FIRST paragraph
 * whatever else they share.
 */
export function composeDescription(i: number, specialty: string): string {
  const bank = SPECIALTY_PARAGRAPHS[specialty];
  if (!bank) {
    throw new RangeError(
      `golden volume: specialty "${specialty}" has no paragraph bank in content.ts`,
    );
  }
  const paragraphs: string[] = [bank[i % 2], bank[2 + (Math.floor(i / 2) % 2)]];
  const count = 3 + (i % 3);
  if (count >= 4) paragraphs.push(bank[4]);
  paragraphs.push(FORMAT_PARAGRAPHS[i % FORMAT_PARAGRAPHS.length] as string);
  if (count >= 5) paragraphs.push(bank[5]);
  return paragraphs.join("\n\n");
}

/** Specialties a programme entry names but no paragraph bank covers. */
export function specialtiesWithoutParagraphBank(): string[] {
  const missing = new Set<string>();
  for (const [, specialty] of VOLUME_PROGRAMME) {
    if (!SPECIALTY_PARAGRAPHS[specialty]) missing.add(specialty);
  }
  return [...missing];
}

